async (page) => {
  await page.goto('http://127.0.0.1:1420/?demo=1&run=1');
  const out = 'output/playwright/script-save-20260914/';
  await page.setViewportSize({ width: 1440, height: 1000 });
  const toolbar = page.locator('.sample-nameplate__script-controls');
  const add = page.getByRole('button', { name: '添加', exact: true });
  const select = toolbar.getByRole('combobox');
  await toolbar.waitFor();
  await page.evaluate(async () => { await Promise.all(document.getAnimations().filter(a => a.effect?.getTiming().iterations !== Infinity).map(a => a.finished.catch(() => {}))); });
  const baseline = await toolbar.boundingBox();
  await add.click();
  const dialog = page.getByRole('dialog', { name: '另存为新脚本' });
  const name = dialog.getByRole('textbox', { name: '脚本名称' });
  if (!(await name.evaluate(el => el === document.activeElement))) throw new Error('Name not focused');
  if (JSON.stringify(baseline) !== JSON.stringify(await toolbar.boundingBox())) throw new Error('Opening shifted toolbar: ' + JSON.stringify({ baseline, opened: await toolbar.boundingBox() }));
  await dialog.getByRole('button', { name: '保存脚本', exact: true }).click();
  if (!(await dialog.getByRole('alert').textContent()).includes('请输入')) throw new Error('Empty name accepted');
  await name.fill('标准测试');
  await dialog.getByRole('button', { name: '保存脚本', exact: true }).click();
  if (!(await dialog.getByRole('alert').textContent()).includes('同名')) throw new Error('Builtin duplicate accepted');
  await name.fill('我的标准测试');
  await dialog.screenshot({ path: out + 'save-dialog.png' });
  await name.press('Enter');
  await dialog.waitFor({ state: 'detached' });
  if (!(await select.textContent()).includes('我的标准测试')) throw new Error('New preset not selected');
  await add.click();
  await name.fill('我的标准测试');
  await dialog.getByRole('button', { name: '保存脚本', exact: true }).click();
  if (!(await dialog.getByRole('alert').textContent()).includes('同名')) throw new Error('Preset duplicate accepted');
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'detached' });
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  const editor = page.getByRole('dialog', { name: '编辑测试设置' });
  const values = editor.getByRole('textbox');
  await values.nth(0).fill('4');
  await editor.getByRole('button', { name: '保存设置', exact: true }).click();
  await editor.waitFor({ state: 'detached' });
  await select.click();
  await page.getByRole('option', { name: '标准测试', exact: true }).click();
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  await values.nth(0).fill('2');
  await editor.getByRole('button', { name: '保存设置', exact: true }).click();
  await editor.waitFor({ state: 'detached' });
  await select.click();
  await page.getByRole('option', { name: '我的标准测试', exact: true }).click();
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  if (await values.nth(0).inputValue() !== '4') throw new Error('Saved preset did not restore edited current');
  await page.keyboard.press('Escape');
  await editor.waitFor({ state: 'detached' });
  const boxes = [];
  for (const width of [900, 1100, 1366, 1440, 1920]) {
    await page.setViewportSize({ width, height: 1000 });
    const rects = await toolbar.locator(':scope > *').evaluateAll(nodes => nodes.map(el => { const r = el.getBoundingClientRect(); return { x:r.x, y:r.y, width:r.width, height:r.height }; }));
    if (rects.some(r => Math.abs(r.y - rects[0].y) > 1 || Math.abs(r.height - rects[0].height) > 1)) throw new Error('Misaligned controls ' + width);
    for (let i = 1; i < rects.length; i++) if (rects[i].x < rects[i-1].x + rects[i-1].width - 1) throw new Error('Overlapping controls ' + width);
    if (await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)) throw new Error('Horizontal overflow ' + width);
    await page.locator('.sample-nameplate').screenshot({ path: out + 'toolbar-' + width + '.png' });
    boxes.push({ width, rects });
  }
  console.log(JSON.stringify({ createAndSelect: true, emptyAndDuplicateRejected: true, editedPresetRestored: true, escapeCloses: true, layout: boxes }));
}
