async (page) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'PIB，点击设置规格', exact: true }).click();
  const spec = page.getByRole('dialog', { name: '设置测试规格', exact: true });
  const half = () => page.getByRole('dialog').locator('.automatic-specification-form').getByRole('textbox').last();
  if (await half().inputValue() !== '1.5') throw new Error('Original half width was not restored');
  await half().fill('2');
  await spec.getByRole('button', { name: '保存规格', exact: true }).click();
  await spec.waitFor({ state: 'detached' });
  await page.getByRole('button', { name: 'PIB，点击设置规格', exact: true }).click();
  if (await half().inputValue() !== '2') throw new Error('Specification did not save');
  await half().fill('3');
  await spec.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('button', { name: 'PIB，点击设置规格', exact: true }).click();
  if (await half().inputValue() !== '2') throw new Error('Cancel changed half width');
  await half().fill('0');
  await spec.getByRole('button', { name: '保存规格', exact: true }).click();
  if (!(await spec.getByRole('alert').textContent()).includes('必须大于 0')) throw new Error('Invalid half width was accepted');
  await half().fill('2');
  await spec.getByRole('button', { name: '保存规格', exact: true }).click();
  await spec.waitFor({ state: 'detached' });
  await page.getByRole('button', { name: 'PIB，点击设置规格', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/test-settings-20260914/pib-specification.png', animations: 'disabled' });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '停止', exact: true }).click();
  await page.getByRole('button', { name: '测试下一台', exact: true }).click();
  await page.getByRole('button', { name: '光谱仪信息，点击打开设置', exact: true }).click();
  const spectrum = page.getByRole('dialog', { name: '光谱仪设置', exact: true });
  if (await spectrum.getByText('PIB 半带宽 (nm)', { exact: true }).count()) throw new Error('Old field still in spectrometer dialog');
  if (!(await spectrum.getByText('PIB 中心波长 (nm)', { exact: true }).isVisible())) throw new Error('PIB center was removed');
  await page.screenshot({ path: 'output/playwright/test-settings-20260914/spectrometer-without-halfwidth.png', animations: 'disabled' });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  const editor = page.getByRole('dialog', { name: '编辑测试设置', exact: true });
  if (await half().inputValue() !== '2') throw new Error('Editor does not share specification');
  await half().fill('2.5');
  await editor.getByRole('button', { name: '保存设置', exact: true }).click();
  await editor.waitFor({ state: 'detached' });
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  if (await half().inputValue() !== '2.5') throw new Error('Editor did not save half width');
  await page.setViewportSize({ width: 900, height: 900 });
  if (await editor.evaluate(n => n.scrollWidth > n.clientWidth)) throw new Error('Editor overflow');
  await page.screenshot({ path: 'output/playwright/test-settings-20260914/pib-editor-900.png', animations: 'disabled' });
  return { originalValueLoaded: true, specificationSave: true, cancel: true, positiveValidation: true, removedFromSpectrometer: true, editorSave: true, noOverflow: true };
}
