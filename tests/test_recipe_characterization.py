class RecipeCharacterizationTests(unittest.TestCase):
    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.backend = HeadlessBackend(JsonSettings(self.root / "settings.json"))
        self.addCleanup(self.backend.export_worker.graceful_stop, 2.0)
        self.station = self.backend.runtime
        self.station.configuration.update({
            "sn": "RECIPE-BASELINE", "outputDir": str(self.root / "output"),
            "powerMeterResource": "ASRL3::INSTR",
        })
        self.station.power_supply_controller = _FakeController()

    def test_plan_is_selected_by_configuration_not_by_display_script_name(self) -> None:
        # The configuration API currently permits standard+custom and hold+range.
        for script in ("standard", "hold-points"):
            for kind in ("ch341", "tdk"):
                for mode in ("range", "custom"):
                    with self.subTest(script=script, kind=kind, mode=mode):
                        self.station.power_supply_kind = kind
                        self.station.configuration.update({
                            "selectedScriptId": script, "powerSupplyKind": kind,
                            "initialCurrentA": 1.0, "targetCurrentA": 7.0,
                            "currentStepA": 3.0, "currentPlanMode": mode,
                            "customCurrentPoints": [
                                {"currentA": 2.0, "dwellS": 30.0},
                                {"currentA": 5.0, "dwellS": 60.0},
                            ],
                        })
                        settings = self.station._automatic_settings()
                        if mode == "range":
                            expected = ((1.0, 4.0, 7.0), (0.0, 0.0, 0.0))
                        elif kind == "tdk":
                            expected = ((2.0, 5.0), (30.0, 60.0))
                        else:
                            expected = ((1.0, 2.0, 4.0, 5.0, 7.0), (0.0, 30.0, 0.0, 60.0, 0.0))
                        self.assertEqual((build_test_currents(settings), build_test_dwells(settings)), expected)
                        self.assertEqual(settings.custom_hold_ramp_enabled, mode == "custom" and kind == "tdk")

    def test_spectrum_depends_on_ready_reader_and_is_never_used_for_aging(self) -> None:
        for script in ("standard", "hold-points", "aging"):
            for ready in (None, False, True):
                with self.subTest(script=script, ready=ready):
                    self.station.configure({"selectedScriptId": script})
                    if script == "hold-points":
                        self.station.configuration["customCurrentPoints"] = [{"currentA": 2.0, "dwellS": 30.0}]
                    self.station.spectrometer_reader = None if ready is None else SimpleNamespace(is_ready=ready)
                    self.assertEqual(self.station._automatic_settings().use_spectrometer, ready is True and script != "aging")

    def test_stability_rule_boundaries_preserve_order_and_absolute_tolerance(self) -> None:
        for script, window in (("standard", 5.0), ("hold-points", 3.0), ("aging", 3.0)):
            # Just below 2 A: power takes the lower band, wavelength takes isclose.
            for current, span, power_window, wavelength in (
                (None, None, window, 0.2), (-0.01, None, window, 0.2),
                (0.0, 0.1, 10.0, 0.2), (1.99, 0.1, 10.0, 0.2),
                (2.0 - 5e-10, 0.1, 10.0, 0.5), (2.0, 0.2, window, 0.5),
                (2.0 + 5e-10, 0.2, window, 0.5), (2.0 + 2e-9, None, window, 0.2),
                (math.nan, None, window, 0.2), (math.inf, None, window, 0.2),
            ):
                with self.subTest(script=script, current=current):
                    self.assertEqual(automatic_power_stability_span_limit_w(current), span)
                    self.assertEqual(automatic_power_stability_window_s(script, 3.0, current), power_window)
                    self.assertEqual(automatic_wavelength_stability_tolerance_nm(current), wavelength)

    def test_standard_window_and_dispatch_keep_their_different_legacy_normalization(self) -> None:
        self.assertEqual(automatic_stability_window_s(" standard ", "unused"), 5.0)
        self.assertEqual(automatic_stability_window_s("STANDARD", "3.5"), 3.5)
        self.station.configuration["selectedScriptId"] = " aging "
        self.assertFalse(self.station._aging_test_selected())
        self.station.configuration["selectedScriptId"] = "aging"
        self.assertTrue(self.station._aging_test_selected())

    def test_confirmation_delay_is_not_the_detector_window_or_custom_dwell(self) -> None:
        self.assertEqual([automatic_post_stable_delay_s(i, 3) for i in range(3)], [5.0, 5.0, 10.0])
        self.assertEqual(automatic_post_stable_delay_s(0, 1), 10.0)
        self.station.configuration.update({"initialCurrentA": 0.6, "pointTimeoutS": 19.9})
        with self.assertRaisesRegex(ValueError, "20.0 s"):
            self.station._automatic_settings()

    def test_trace_creation_follows_resolved_settings_and_tdk_not_script_label(self) -> None:
        for script in ("standard", "hold-points"):
            self.station.configuration["selectedScriptId"] = script
            for kind in ("ch341", "tdk"):
                self.station.power_supply_kind = kind
                for mode in ("range", "custom"):
                    with self.subTest(script=script, kind=kind, mode=mode):
                        # Preserve this callable's settings input, even if configuration differs.
                        settings = AutomaticTestSettings(current_plan_mode=mode)
                        with patch("tauri_bridge.station_automatic.AutomaticSampleRecorder") as recorder:
                            self.station._begin_recording_session(settings)
                            self.assertEqual(recorder.call_count, int(kind == "tdk" and mode == "custom"))
                        self.station._close_automatic_sample_recorder()

    def test_aging_does_not_create_an_ordinary_point_journal_or_spectrum_session(self) -> None:
        self.station.power_meter_reader = MagicMock(is_ready=True)
        self.station.spectrometer_reader = MagicMock(is_ready=True)
        with (
            patch("tauri_bridge.station_automatic.threading.Thread"),
            patch.object(self.station, "_begin_recording_session") as begin,
            patch.object(self.station, "start_spectrometer") as start_spectrum,
        ):
            self.station.start_automatic({"selectedScriptId": "aging"})
        begin.assert_not_called()
        start_spectrum.assert_not_called()
        self.assertIsNone(self.station.record_store.current_session)
        self.assertIsNone(self.station.automatic_sample_recorder)
        self.assertFalse(self.station.automatic.settings.use_spectrometer)
        self.assertEqual(self.station.automatic.currents, tuple(float(i) for i in range(2, 21, 2)))

    def test_unknown_script_and_unsupported_aging_controller_remain_blocked(self) -> None:
        self.station.configuration["selectedScriptId"] = "not-a-recipe"
        self.assertIn("invalid_script", {b["code"] for b in self.station.automatic_readiness()["blockers"]})
        with self.assertRaisesRegex(ValueError, "仅支持 CH341"):
            self.station.configure({"selectedScriptId": "aging", "powerSupplyKind": "tdk"})

    def _run_with_failed_first_commit(self, *, abort: bool) -> list[tuple[str, float]]:
        station = self.station
        station.power_supply_kind = "tdk"
        station.configuration.update({"initialCurrentA": 2.0, "targetCurrentA": 4.0, "currentStepA": 2.0})
        settings = station._automatic_settings()
        station.automatic.start(settings, power_meter_ready=True, spectrum_meter_ready=False)
        station._begin_recording_session(settings)
        reading = PowerMeterReading(5.0, 4.0, True, 0.01, 5.0, 4.0, stability_percent=0.1)
        events: list[tuple[str, float]] = []
        real_append = station.record_store._journal.append
        failed = False
        real_fsync = os.fsync

        def append(event):
            nonlocal failed
            if event["type"] == "point_committed" and not failed:
                failed = True
                events.append(("write_failed", event["record"].current_a))
                raise SessionJournalError("injected disk failure")
            real_append(event)
            if event["type"] == "point_committed":
                events.append(("committed", event["record"].current_a))

        def set_current(current):
            if current == 4.0:
                self.assertIn(("committed", 2.0), events)
                self.assertIn(2.0, station.record_store.recorded_currents)
            station.active_current_a = current
            events.append(("set", current))

        def notify(_level, _title, _message, **_kwargs):
            if station.automatic_pause_kind == "record_persistence_failed":
                self.assertEqual(station.automatic.current_index, 0)
                self.assertEqual(station.record_store.recorded_currents, set())
                self.assertEqual(station.record_store.list_attempts(station.record_store.current_session.session_id), ())
                self.assertNotIn(("set", 4.0), events)
                if abort:
                    station.automatic_terminal_reason = "操作者提前结束测试"
                    station._automatic_stop.set()
                    station._automatic_resume.set()
                else:
                    station.resume_automatic("retry_persist")

        def shutdown():
            station.shutdown_confirmed = True
            events.append(("shutdown", 0.0))

        with (
            patch.object(station, "_wait_for_automatic_acquisition"),
            patch.object(station, "_set_automatic_current", side_effect=set_current),
            patch.object(station, "_wait_for_automatic_stability", return_value=(reading, None, 0, 0)),
            patch.object(station, "_wait_for_automatic_stable_hold", return_value=(reading, None)),
            patch.object(station, "_schedule_pause_safety_timeout"),
            patch.object(station, "notify", side_effect=notify),
            patch.object(station, "safe_ramp_down", side_effect=shutdown),
            patch.object(station, "_queue_automatic_export"),
            patch.object(station.record_store._journal, "append", side_effect=append),
            patch("combined_test.session_journal.os.fsync", wraps=real_fsync) as fsync,
        ):
            station._run_automatic()
        self.assertTrue(failed)
        self.assertGreaterEqual(fsync.call_count, 1)
        self.assertEqual(station.automatic.state, AutomaticTestState.COMPLETED)
        self.assertIn(("shutdown", 0.0), events)
        return events

    def test_real_point_loop_retries_commit_before_next_current(self) -> None:
        self.assertEqual(self._run_with_failed_first_commit(abort=False), [
            ("set", 2.0), ("write_failed", 2.0), ("committed", 2.0),
            ("set", 4.0), ("committed", 4.0), ("shutdown", 0.0),
        ])
        self.assertEqual(self.station.automatic_terminal_outcome, "succeeded")
        events = [json.loads(line) for line in self.station.record_store.journal_path.read_text().splitlines()]
        self.assertEqual([e["type"] for e in events], ["session_start", "point_committed", "point_committed", "session_completed"])

    def test_operator_abort_after_failed_commit_never_sets_next_current(self) -> None:
        events = self._run_with_failed_first_commit(abort=True)
        self.assertNotIn(("set", 4.0), events)
        self.assertEqual(self.station.record_store.recorded_currents, set())
        self.assertEqual(self.station.automatic_terminal_outcome, "stopped_shutdown_confirmed")

    def test_failed_replacement_preserves_selected_attempt_and_retry_history(self) -> None:
        store = self.station.record_store
        store.begin_session(self.root / "excel", "ATTEMPTS", datetime.now())
        record = ExcelTestRecord(2, 12, 4, 1/6, 976, 976, 1, .95, [975, 976], [1, 9])
        store.queue(record)
        store.record_invalid_attempt(2, AttemptValidity.SATURATED, "clipped")
        session_id = store.current_session.session_id
        before = store.list_attempts(session_id)
        with patch.object(store._journal, "append", side_effect=SessionJournalError("disk full")):
            with self.assertRaises(SessionJournalError):
                store.queue(replace(record, power_w=4.1))
        self.assertEqual(store.list_attempts(session_id), before)
        store.queue(replace(record, power_w=4.1))
        attempts = store.list_attempts(session_id)
        self.assertEqual([a.attempt_no for a in attempts], [1, 2, 3])
        self.assertEqual([a.selected for a in attempts], [False, False, True])
        self.assertEqual(attempts[1].validity, AttemptValidity.SATURATED)


